-- Reparo do `id` sem sequence (v1.9.4): a criação parcial também deixou o
-- `id` da tabela `pontos` sem IDENTITY e sem DEFAULT — as leituras
-- funcionavam, mas bater o ponto (INSERT) falhava com
-- 'null value in column "id" ... violates not-null constraint'.
-- Se o id estiver sem identity e sem default, cria a sequence, liga o
-- DEFAULT e sincroniza pelo maior id existente. Com identity (instalação
-- normal), este bloco não faz nada.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'pontos' AND column_name = 'id'
      AND is_identity = 'NO'
  ) THEN
    CREATE SEQUENCE IF NOT EXISTS pontos_id_seq;
    ALTER TABLE pontos ALTER COLUMN id SET DEFAULT nextval('pontos_id_seq');
    ALTER SEQUENCE pontos_id_seq OWNED BY pontos.id;
    PERFORM setval('pontos_id_seq', COALESCE((SELECT MAX(id) FROM pontos), 0) + 1, false);
  END IF;
END $$;

